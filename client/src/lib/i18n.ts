// Lower-case index for case-insensitive lookups (sentence fragments are often
// lower-cased by the engine, e.g. "landholding farmer families").
const lowerValueDict: Record<string, string> = {};
for (const k in hiValueDict) {
  lowerValueDict[k.toLowerCase()] = hiValueDict[k];
}

export function translateValue(language: Language, value: string): string {
  if (language === 'en') return value;
  const trimmed = value.trim();
  if (trimmed in hiValueDict) return hiValueDict[trimmed];
  const lower = lowerValueDict[trimmed.toLowerCase()];
  if (lower !== undefined) return lower;
  return value;
}

function translateGroupPhrase(language: Language, phrase: string): string {
  return phrase
    .split(/\s+or\s+/)
    .map((part) => translateValue(language, part).trim())
    .filter(Boolean)
    .join(' या ');
}

// Translates a full generated sentence. Handles the fixed templates exactly and
// the few templates that interpolate values (occupation / target group / age).
// Unknown strings are returned unchanged so English output is never degraded.
export function translateDetail(language: Language, sentence: string): string {
  if (language === 'en') return sentence;
  const exact = hiValueDict[sentence];
  if (exact !== undefined) return exact;

  const tv = (s: string) => translateValue(language, s);

  let m = sentence.match(/^Your main activity \((.+)\) matches (.+)\.$/);
  if (m) return `आपकी मुख्य गतिविधि (${tv(m[1])}) ${translateGroupPhrase(language, m[2])} से मेल खाती है।`;

  m = sentence.match(/^This opportunity is intended for (.+), which your main activity \((.+)\) does not fit\.$/);
  if (m) return `यह अवसर ${translateGroupPhrase(language, m[1])} के लिए है, जो आपकी मुख्य गतिविधि (${tv(m[2])}) से मेल नहीं खाता।`;

  m = sentence.match(/^We could not confirm (.+) from your profile yet\s*[\u2014-]\s*you can complete this in [“"](.*?)[”"]\.$/);
  if (m) return `अभी आपकी प्रोफाइल से ${translateGroupPhrase(language, m[1])} की पुष्टि नहीं हो सकी — आप इसे “${tv(m[2])}” अनुभाग में पूरा कर सकते हैं।`;

  m = sentence.match(/^Your age group matches the (\d+)-(\d+)(\+?)\s*range for this opportunity\.$/);
  if (m) return `आपका आयु वर्ग इस अवसर के लिए ${m[1]}-${m[2]}${m[3] ? '+' : ''} आयु सीमा से मेल खाता है।`;

  m = sentence.match(/^This opportunity is meant for ages (\d+)-(\d+)(\+?), and your age group is outside that range\.$/);
  if (m) return `यह अवसर ${m[1]}-${m[2]}${m[3] ? '+' : ''} आयु के लिए है, और आपका आयु वर्ग इस सीमा से बाहर है।`;

  m = sentence.match(/^This opportunity is aimed at ages (\d+)-(\d+)(\+?); your age group falls outside\.$/);
  if (m) return `यह अवसर ${m[1]}-${m[2]}${m[3] ? '+' : ''} आयु को ध्यान में रखकर बनाया गया है; आपका आयु वर्ग इससे बाहर है।`;

  return sentence;
}

